export type ExecutiveFilters = {
    year: number;
    cycle: string;
    partner: string;
    region: string;
    farm: string;
    commodity: string;
};
export type ExecutivePricing = {
    sellingPrice: number;
    hpp: number;
    transport: number;
};
export type ExecutiveFarm = {
    id: string;
    name: string;
    city: string;
    region: string;
    partnerId: string;
    partnerName: string;
    landCategory: string;
    areaHa: number;
    commodityIds: string[];
    latitude: number | null;
    longitude: number | null;
    detail_url: string;
};
export type ExecutiveRow = {
    id: string;
    farmId: string;
    year: number;
    cycle: string;
    farm: ExecutiveFarm;
    partner: { id: string; name: string };
    commodity: { id: string; name: string; pricing: ExecutivePricing | null };
    plantedHa: number;
    harvestedTon: number;
    projectedTon: number | null;
    projectionMissing: number;
    stockTon: number | null;
    monthlyDeliveredTon: number;
    status: string;
    contract?: { status: string; monthlyTon: number };
    client?: { id: string; name: string };
};
export type ExecutiveSummaryData = {
    updatedAt: string;
    snapshotAt: string;
    defaultYear: number;
    referenceMonth: number;
    filters: ExecutiveFilters;
    years: number[];
    cycles: { id: string; name: string }[];
    farms: ExecutiveFarm[];
    commodities: { id: string; name: string }[];
    partners: { id: string; name: string }[];
    clients: { id: string; name: string }[];
    rows: ExecutiveRow[];
};
